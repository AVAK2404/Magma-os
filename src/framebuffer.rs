//! Framebuffer driver for Magma OS
//! Uses Limine FramebufferRequest to obtain display information

use spin::Once;

pub static FRAMEBUFFER: Once<Framebuffer> = Once::new();

/// Framebuffer representation
pub struct Framebuffer {
    base_addr: usize,
    pitch: usize,
    width: usize,
    height: usize,
    bpp: usize,
}

impl Framebuffer {
    /// Initialize the framebuffer from Limine request
    pub fn new(entry: &limine::framebuffer::Framebuffer) -> Self {
        Framebuffer {
            base_addr: entry.address() as usize,
            pitch: entry.pitch as usize,
            width: entry.width as usize,
            height: entry.height as usize,
            bpp: entry.bpp as usize,
        }
    }

    /// Calculate pixel address at (x, y)
    fn pixel_addr(&self, x: usize, y: usize) -> *mut u32 {
        if x >= self.width || y >= self.height {
            return core::ptr::null_mut();
        }
        unsafe {
            ((self.base_addr as *mut u8).add(y * self.pitch + x * 4)) as *mut u32
        }
    }

    /// Clear the entire framebuffer to a color
    pub fn clear(&self, color: u32) {
        for y in 0..self.height {
            for x in 0..self.width {
                unsafe {
                    let pixel = self.pixel_addr(x, y);
                    if !pixel.is_null() {
                        core::ptr::write(pixel, color);
                    }
                }
            }
        }
    }

    /// Fill a rectangle with a color
    pub fn fill_rect(&self, x: usize, y: usize, w: usize, h: usize, color: u32) {
        for row in y..core::cmp::min(y + h, self.height) {
            for col in x..core::cmp::min(x + w, self.width) {
                unsafe {
                    let pixel = self.pixel_addr(col, row);
                    if !pixel.is_null() {
                        core::ptr::write(pixel, color);
                    }
                }
            }
        }
    }

    /// Draw a single pixel
    pub fn put_pixel(&self, x: usize, y: usize, color: u32) {
        unsafe {
            let pixel = self.pixel_addr(x, y);
            if !pixel.is_null() {
                core::ptr::write(pixel, color);
            }
        }
    }

    /// Get framebuffer dimensions
    pub fn dimensions(&self) -> (usize, usize) {
        (self.width, self.height)
    }

    /// Get width
    pub fn width(&self) -> usize {
        self.width
    }

    /// Get height
    pub fn height(&self) -> usize {
        self.height
    }

    /// Draw a scaled character at position (x, y)
    /// Each glyph bit renders as a scale x scale pixel block
    /// Advances x by 8 * scale pixels per character
    pub fn draw_char_scaled(&self, x: usize, y: usize, c: char, fg: u32, bg: u32, scale: usize) {
        if scale == 0 { return; }
        if let Some((bitmap, _)) = char_to_bitmap(c) {
            for row in 0..8 {
                for bit in 0..8 {
                    let pixel_color = if (bitmap[row] >> bit) & 1 != 0 { fg } else { bg };
                    let px = x + bit * scale;
                    let py = y + row * scale;
                    self.fill_rect(px, py, scale, scale, pixel_color);
                }
            }
        }
    }

    /// Draw a scaled string at position (x, y)
    /// Each character advances x by 8 * scale pixels
    pub fn draw_str_scaled(&self, x: usize, y: usize, s: &str, fg: u32, bg: u32, scale: usize) {
        let mut current_x = x;
        for c in s.chars() {
            self.draw_char_scaled(current_x, y, c, fg, bg, scale);
            current_x += 8 * scale;
        }
    }

    /// Draw a string at position (x, y)
    pub fn draw_str(&self, x: usize, y: usize, s: &str, fg_color: u32) {
        self.draw_str_scaled(x, y, s, fg_color, 0x000000, 1);
    }
}

