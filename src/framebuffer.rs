/// Convert ASCII character to bitmap
fn char_to_bitmap(c: char) -> Option<(&'static [u8; 8], usize)> {
    match c {
        ' '..='~' => Some((&FONT_8X8[(c as usize) - 32], 8)),
        '\n' => Some((&[0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00], 0)),
        '\r' => Some((&[0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00], 8)),
        _ => None,
    }
}

/// Internal function to draw a bitmap character
#[allow(dead_code)]
fn draw_char_bitmap(fb: &Framebuffer, x: usize, y: usize, bitmap: &[u8; 8], color: u32) {
    for (row, &byte) in bitmap.iter().enumerate() {
        for bit in 0..8 {
            if (byte >> bit) & 1 != 0 {
                fb.put_pixel(x + bit, y + row, color);
            }
        }
    }
}

/// Initialize the framebuffer subsystem
pub fn init(entry: &limine::framebuffer::Framebuffer) {
    FRAMEBUFFER.call_once(|| Framebuffer::new(entry));
}